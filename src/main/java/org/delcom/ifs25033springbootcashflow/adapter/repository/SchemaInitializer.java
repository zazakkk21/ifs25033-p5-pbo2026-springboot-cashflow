package org.delcom.ifs25033springbootcashflow.adapter.repository;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

public final class SchemaInitializer {
    private SchemaInitializer() {
    }

    public static void initialize(DataSource dataSource) {
        String[] statements = {
                """
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    username VARCHAR(100) NOT NULL UNIQUE,
                    password_hash VARCHAR(255) NOT NULL,
                    full_name VARCHAR(200) NOT NULL,
                    role VARCHAR(20) NOT NULL,
                    photo_path VARCHAR(500)
                )
                """,
                """
                CREATE TABLE IF NOT EXISTS transactions (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    description TEXT NOT NULL,
                    amount BIGINT NOT NULL,
                    type VARCHAR(20) NOT NULL,
                    proof_path VARCHAR(500),
                    created_at TIMESTAMP NOT NULL,
                    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
                )
                """,
                "CREATE INDEX IF NOT EXISTS idx_transactions_user_created ON transactions(user_id, created_at DESC, id DESC)",
                "CREATE INDEX IF NOT EXISTS idx_transactions_user_amount ON transactions(user_id, amount)"
        };
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            for (String sql : statements) {
                statement.execute(sql);
            }
        } catch (SQLException exception) {
            throw new IllegalStateException("Gagal menyiapkan tabel cashflow", exception);
        }
    }
}
